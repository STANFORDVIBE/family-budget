/// Inserts missing currencies. Safe to run on every start.
pub fn currencies(conn: &Connection) -> AppResult<()> {
    let mut stmt =
        conn.prepare("INSERT OR IGNORE INTO currencies (code, name, symbol, decimals) VALUES (?1, ?2, ?3, ?4)")?;
    for (code, name, symbol, decimals) in CURRENCIES {
        stmt.execute(params![code, name, symbol, decimals])?;
    }
    Ok(())
}
